function caps(list) {
  return list.map((item, i) => ({
    n: String(i + 1).padStart(2, '0'),
    image: item.image || imgs[i % imgs.length],
    title: item.title,
    text: item.text,
  }))
}

export function buildService({
  slug,
  category,
  name,
  crumbs,
  intro,
  extra,
  cta,
  heroNote,
  heroImage,
  capabilitiesTitle,
  capabilities,
  elementsTitle,
  elements,
  deliverables,
  why,
  bannerTitle,
  hub,
  children,
}) {
  return {
    slug,
    category,
    name,
    breadcrumb: crumbs,
    intro,
    extra,
    cta: cta || `Discuss Your ${category} Project`,
    heroNote: heroNote || ['Accurate.', 'Coordinated.', 'Delivery-ready.'],
    heroImage: heroImage || imgs[2],
    capabilitiesTitle: capabilitiesTitle || `Our ${category} Capabilities`,
    capabilities: caps(capabilities || children?.map((c) => ({ title: c.title, text: c.text })) || []),
    elementsTitle: elementsTitle || 'What We Cover',
    elements: elements || [
      { title: 'Data capture', text: 'Survey, drawings or model inputs as agreed', icon: 'scan' },
      { title: 'Modelling', text: 'Accurate 2D/3D production to project standards', icon: 'cube' },
      { title: 'Coordination', text: 'Clash review and multidisciplinary alignment', icon: 'layers' },
      { title: 'Documentation', text: 'Drawings, schedules and agreed exports', icon: 'draft' },
    ],
    deliverablesTitle: 'Our Deliverables',
    deliverables: deliverables || [
      'Agreed 2D/3D models and drawings',
      'Updated revisions through the project cycle',
      'Coordination support and issue logs, where in scope',
      'Exports in RVT, IFC, DWG or other agreed formats',
    ],
    industries,
    why: why || defaultWhy,
    bannerTitle: bannerTitle || `Need support with ${name}?`,
    hub: Boolean(hub),
    children: children || [],
  }
}

