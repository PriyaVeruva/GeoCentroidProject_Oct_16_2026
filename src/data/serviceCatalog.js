function caps(list) {
  return list.map((item, i) => ({
    n: String(i + 1).padStart(2, '0'),
    image: item.image || imgs[i % imgs.length],
    title: item.title,
    text: item.text,
    to: item.to,
  }))
}

export function buildService({
  slug,
  category,
  name,
  crumbs,
  intro,
  extra,
  cta,
  heroNote,
  heroImage,
  capabilitiesTitle,
  capabilities,
  elementsTitle,
  elements,
  deliverables,
  why,
  bannerTitle,
  bannerText,
  hub,
  children,
}) {
  return {
    slug,
    category,
    name,
    breadcrumb: crumbs,
    intro,
    extra,
    cta: cta || `Discuss Your ${name} Project`,
    heroNote,
    heroImage: heroImage || imgs[2],
    capabilitiesTitle: capabilitiesTitle || `Our ${name} Capabilities`,
    capabilities: caps(capabilities || children?.map((c) => ({ title: c.title, text: c.text, to: c.to })) || []),
    elementsTitle,
    elements,
    deliverablesTitle: 'Our Deliverables',
    deliverables,
    industries,
    why,
    bannerTitle: bannerTitle || `Need support with ${name}?`,
    bannerText:
      bannerText ||
      'Share your project scope, source data and delivery requirements with our team to discuss a suitable approach.',
    hub: Boolean(hub),
    children: children || [],
  }
}

